private fun mail(
    id: String,
    accountId: String,
    from: String,
    subject: String,
    preview: String,
    body: String,
    time: Long,
    unread: Boolean,
    type: MailType?,
    tags: List<MailTag>,
    folder: Folder = Folder.Inbox,
): Mail = Mail(
    id = id,
    accountId = accountId,
    folder = folder,
    fromName = from,
    subject = subject,
    preview = preview,
    body = body,
    timeMillis = time,
    unread = unread,
    type = type,
    tags = tags,
)
