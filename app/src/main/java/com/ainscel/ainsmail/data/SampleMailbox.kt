private fun mail(
    id: String,
    accountId: String,
    from: String,
    subject: String,
    preview: String,
    body: String,
    time: Long,
    unread: Boolean,
    type: MailType?,
    tagNames: List<String> = emptyList(),
    remoteFolder: RemoteFolder = RemoteFolder.Inbox,
    archived: Boolean = false,
): Mail = Mail(
    id = id,
    accountId = accountId,
    remoteFolder = remoteFolder,
    archived = archived,
    fromName = from,
    subject = subject,
    preview = preview,
    body = body,
    timeMillis = time,
    unread = unread,
    type = type,
    tagNames = tagNames,
)
